#!/usr/bin/env node
/**
 * Generate public/_redirects — the Cloudflare Pages redirect rules file.
 *
 * Cloudflare Pages evaluates `_redirects` at the edge before any static
 * asset lookup, so this is what actually serves a real, single-hop
 * server-side 301 for /init, /setup, /onboarding, and /docs (and their
 * per-language variants) — the HTML meta-refresh page Astro's static build
 * renders for the same routes (via the `redirects` option in
 * astro.config.mjs) is a client-side fallback only, never what a
 * non-browser agent or crawler should be relied on to follow.
 *
 * Source of truth (parsed from source, not imported — plain Node script,
 * no Vite/TS loader):
 *   - src/lib/redirect-map.ts       REDIRECT_PAIRS (unprefixed from/to pairs)
 *   - src/lib/language-codes.ts     LANGUAGE_CODES + DEFAULT_LANGUAGE_CODE
 *
 * Idempotent: the output is rewritten only when it differs.
 * Run automatically as part of `prebuild` (see package.json).
 *
 * Run standalone: `node scripts/generate-redirects.mjs`
 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUT_PATH = resolve(ROOT, 'public/_redirects');

async function readLanguageCodes() {
  const src = await readFile(
    resolve(ROOT, 'src/lib/language-codes.ts'),
    'utf8'
  );
  const listMatch = src.match(/LANGUAGE_CODES\s*=\s*\[([^\]]*)\]/s);
  if (!listMatch) {
    throw new Error(
      'LANGUAGE_CODES array not found in src/lib/language-codes.ts'
    );
  }
  const codes = [...listMatch[1].matchAll(/'([a-z-]+)'/g)].map((m) => m[1]);

  const defaultMatch = src.match(/DEFAULT_LANGUAGE_CODE\s*=\s*'([a-z-]+)'/);
  if (!defaultMatch) {
    throw new Error(
      'DEFAULT_LANGUAGE_CODE not found in src/lib/language-codes.ts'
    );
  }
  return { codes, defaultCode: defaultMatch[1] };
}

async function readRedirectPairs() {
  const src = await readFile(resolve(ROOT, 'src/lib/redirect-map.ts'), 'utf8');
  const listMatch = src.match(/REDIRECT_PAIRS[^=]*=\s*\[([\s\S]*?)\n\];/);
  if (!listMatch) {
    throw new Error(
      'REDIRECT_PAIRS array not found in src/lib/redirect-map.ts'
    );
  }
  const entryPattern =
    /\{\s*from:\s*'([a-z-]+)',\s*to:\s*'([a-z-]+)',\s*status:\s*(\d+)\s*\}/g;
  const pairs = [...listMatch[1].matchAll(entryPattern)].map((m) => ({
    from: m[1],
    to: m[2],
    status: Number(m[3]),
  }));
  if (pairs.length === 0) {
    throw new Error('No redirect pairs parsed from src/lib/redirect-map.ts');
  }
  return pairs;
}

async function main() {
  const [{ codes, defaultCode }, pairs] = await Promise.all([
    readLanguageCodes(),
    readRedirectPairs(),
  ]);

  const lines = [
    '# Cloudflare Pages redirects',
    '# https://developers.cloudflare.com/pages/configuration/redirects/',
    '#',
    '# Generated by scripts/generate-redirects.mjs from src/lib/redirect-map.ts',
    '# + src/lib/language-codes.ts — do not hand-edit; re-run the generator.',
    '# Served at the edge before any static asset lookup: a real, single-hop',
    '# server-side redirect (not the HTML meta-refresh page Astro also',
    '# renders for these same routes as a client-side fallback).',
    '',
  ];

  for (const code of codes) {
    const prefix = code === defaultCode ? '' : `/${code}`;
    for (const { from, to, status } of pairs) {
      lines.push(`${prefix}/${from} ${prefix}/${to} ${status}`);
    }
  }
  lines.push('');

  const content = lines.join('\n');
  const existing = await readFile(OUT_PATH, 'utf8').catch(() => null);
  if (existing === content) {
    console.log('[generate-redirects] public/_redirects already up to date');
    return;
  }
  await writeFile(OUT_PATH, content, 'utf8');
  console.log(
    `[generate-redirects] wrote public/_redirects (${codes.length} languages × ${pairs.length} rules = ${codes.length * pairs.length} redirects)`
  );
}

main().catch((err) => {
  console.error('[generate-redirects] failed:', err);
  process.exitCode = 1;
});
